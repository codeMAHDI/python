# Single Qoute Single qoute is used to define a string in Python. It is a common way to create string literals. Here are some examples of how to use single quotes to define strings:
# single('') double("") and triple quotes (''' ''') or (""" """) are all used to define strings in Python. Each type of quote has its own advantages and use cases. Single quotes are often used when you want to include double quotes within the string without needing to escape them, while double quotes are useful when you want to include single quotes. Triple quotes are typically used for multi-line strings or docstrings.
# Example 1: Using single quotes to define a string(For short strings without special characters)
string1 = 'Hello, World!'
print(string1)  # Output: Hello, World!


# Example 2: Using single quotes to include double quotes in a string
string2 = 'She said, "Hello!"'
print(string2)  # Output: She said, "Hello!"


# Example 3: Using single quotes to include an apostrophe in a string
string3 = 'It\'s a beautiful day!'
print(string3)  # Output: It's a beautiful day!


# Example 4: Using single quotes to define a multi-line string
string4 = 'This is a multi-line string.\nIt can span multiple lines.'
print(string4)
# Output:
# This is a multi-line string.
# It can span multiple lines.
# Example 5: Using single quotes to define an empty string
string5 = ''
print(string5)  # Output: (an empty string)
# In summary, single quotes are a convenient way to define strings in Python, especially when you want to include double quotes or apostrophes without needing to escape them.
